"""Day 1 · Challenge：一个带记忆的命令行 AI 对话程序。

它比 main.py 多了两个关键能力：

    1. Streaming        —— 回答逐字显示（体验）
    2. Conversation History —— 记住上下文（**这是 Agent Memory 的最初形态**）

为什么「记忆」这么重要？

    大模型 API 是**无状态**的。你不把历史发过去，它就完全不知道刚才聊了什么：

        第 1 轮  发送：[我叫 Jack]                      → 回答「你好 Jack」
        第 2 轮  发送：[我叫什么？]                     → 回答「我不知道你叫什么」
        第 2 轮  发送：[我叫 Jack, 你叫... , 我叫什么？] → 回答「你叫 Jack」

    所以「记忆」不是模型记住了，而是**我们每一轮都把历史重新发了一遍**。

Java 类比
    这个 messages 列表 ≈ 存在 Redis 里的会话上下文
    （对应 Spring Session / ChatMemory）

运行：
    uv run python chat.py                 # 流式输出（默认）
    uv run python chat.py --no-stream     # 一次性输出，方便看 token 用量
    uv run python chat.py --system "你是一个仅用古文回答的助手"

对话中的命令：
    /clear    清空上下文，重新开始
    /history  查看当前上下文条数
    /help     查看帮助
    exit      退出
"""

# ---------------------------------------------------------------
#  为什么写这行？
#  它让「类型注解」变成延迟求值 —— 于是可以写 list[Message] 这种
#  新语法，即使运行在 Python 3.9 上也不会报错。
#  凡是用了新式注解语法的文件，都建议加上它。
# ---------------------------------------------------------------
from __future__ import annotations

import argparse  # 标准库：解析命令行参数（相当于 Java 的 args 手动解析，但更规范）
import sys  # 标准库：sys.exit() 退出程序并返回状态码
import time  # 标准库：计时用

from llm_client import LLMClient, LLMError, Message

# ---------------------------------------------------------------
#  系统提示词（system prompt）
#
#  它不参与「你问我答」，而是告诉模型：你是谁的、用什么风格说话。
#  相当于给演员一份人物小传，之后所有台词都按这个人设来演。
#
#  工程上把它抽成模块级常量，而不是散在代码里硬编码 ——
#  这样想换人设时只改一处，也方便被命令行参数覆盖（见 --system）。
# ---------------------------------------------------------------
DEFAULT_SYSTEM_PROMPT = (
    "你是一位耐心、务实的技术导师，面向有 Java 后端工程背景的工程师讲解 AI 知识。"
    "回答要简洁准确，善用 Java 世界的类比帮助理解，不要啰嗦。"
)

# ---------------------------------------------------------------
#  为什么用集合 {} 而不是列表 []？
#
#  集合的查找是 O(1)，列表是 O(1)~O(n) 线性扫描。
#  这里要频繁做「输入的词在不在退出词里」的判断，用集合更合适。
#
#  为什么写这么多个同义词？
#  用户体验 —— 有人习惯敲 quit，有人习惯 :q（vim 用户），
#  全部接受，避免「敲了 quit 却没反应」的困惑。
#
#  Java 类比：Set<String> EXIT_WORDS = Set.of("exit", "quit", ...);
# ---------------------------------------------------------------
EXIT_WORDS = {"exit", "quit", "bye", "/exit", "/quit", ":q"}

# 帮助文本。用三引号字符串（Python 的多行字符串），
# 相当于 Java 15+ 的 text block（""" ... """）。
# .strip() 是为了去掉开头/结尾多余的换行。
HELP_TEXT = """
可用命令：
  /clear    清空上下文，重新开始对话
  /history  查看当前上下文条数与内容概览
  /help     显示本帮助
  exit      退出程序
""".strip()


def parse_args() -> argparse.Namespace:
    """解析命令行参数。

    这是 Python 里处理命令行参数的标准做法。
    相当于 Java 里用 picocli / args4j / Spring Shell，
    但 argparse 是标准库自带的，不用额外装依赖。

    它会自动生成 --help 说明，并且处理参数缺失、类型错误等情况。

    Returns:
        一个类似 Java 里 Map/DTO 的对象，用 args.xxx 取字段值。
    """
    # description 会显示在 `python chat.py --help` 的输出里
    parser = argparse.ArgumentParser(description="命令行 AI 对话（带上下文记忆）")

    # -----------------------------------------------------------
    #  --no-stream 是一个「开关」（boolean flag）
    #
    #  action="store_true" 的含义：
    #      命令里【没有】--no-stream  → 值为 False
    #      命令里【写了】--no-stream  → 值为 True
    #
    #  注意命名上的小技巧：我们想表达的是「关掉流式」这个动作，
    #  所以叫 --no-stream 而不是 --stream。因为开关默认是关的，
    #  想要「关掉流式」就必须表达成一个「要去打开」的动作。
    #  （默认值就是流式开启，符合大多数人预期的体验）
    #
    #  Java 类比：@Option(names = "--no-stream") boolean noStream;
    # -----------------------------------------------------------
    parser.add_argument(
        "--no-stream",
        action="store_true",
        help="关闭流式输出（一次性返回，便于查看 token 用量）",
    )

    # -----------------------------------------------------------
    #  --system 让用户自定义人设
    #
    #  default=... 指定默认值。用户不传这个参数时，
    #  args.system 就等于 DEFAULT_SYSTEM_PROMPT。
    #
    #  用法示例（PowerShell）：
    #      uv run python chat.py --system "你是一个只用古文回答的助手"
    #
    #  ⚠️ 注意：PowerShell 里给参数传含中文的值时，
    #     整个 --system "中文..." 部分要用引号包住，
    #     否则中文可能被终端按错误编码处理。
    # -----------------------------------------------------------
    parser.add_argument(
        "--system",
        default=DEFAULT_SYSTEM_PROMPT,
        help="自定义系统提示词",
    )

    # parse_args() 会真正去读 sys.argv（命令行上敲的那些词），
    # 解析后返回一个对象。
    return parser.parse_args()


def show_history(messages: list[Message]) -> None:
    """打印当前上下文概览，肉眼确认「记忆」确实在累积。

    这个函数纯粹是为了「教学可观测性」——
    让你能亲眼看到模型每轮到底收到了什么。
    真实产品里不会给最终用户看这个，但开发调试时非常有用。

    Args:
        messages: 完整上下文列表，每项形如
                  {"role": "user", "content": "..."}
    """
    # 边界情况：列表可能是空的（比如刚 /clear 过，且没设 system）
    if not messages:
        print("[上下文为空]")
        return  # 提前返回，相当于 Java 里的 guard clause

    print(f"[当前上下文共 {len(messages)} 条]")

    # ---------------------------------------------------------------
    #  enumerate(messages, 1) 是 Python 里「带序号遍历」的写法：
    #      普通遍历：for msg in messages:           → 只有元素
    #      enumerate：for i, msg in enumerate(...)  → 同时拿到序号和元素
    #
    #  第二个参数 1 表示序号【从 1 开始数】（默认是 0）。
    #  这是给人看的，从 1 数更自然。
    #
    #  如果不用 enumerate，就得自己维护计数器：
    #      i = 1
    #      for msg in messages:
    #          ...
    #          i += 1
    #  Python 的哲学是「不写这种样板代码」。
    #
    #  Java 类比：for (int i = 0; i < list.size(); i++) 里的 i，
    #             但 Python 把它做成了语言内置能力。
    # ---------------------------------------------------------------
    for i, msg in enumerate(messages, 1):
        # replace("\n", " ")：把内容里的换行压成空格，
        # 否则多行回答会把整个列表撑得很乱
        content = msg["content"].replace("\n", " ")

        # -----------------------------------------------------------
        #  只截取前 36 个字符做预览
        #
        #  这行是「切片」+「条件表达式」的组合，拆开看：
        #
        #      content[:36]              切片：取前 36 个字符
        #                                （Python 切片是左闭右开，
        #                                  索引越界也不报错，最多给到末尾）
        #
        #      ("..." if len(content) > 36 else "")
        #                                条件表达式（三元运算符）
        #                                相当于 Java 的
        #                                len > 36 ? "..." : ""
        #                                注意 Python 的写法是：
        #                                  值A if 条件 else 值B
        #                                和 Java 的顺序不同
        preview = content[:36] + ("..." if len(content) > 36 else "")

        # -----------------------------------------------------------
        #  f-string 里的格式规范 —— {msg['role']:<9}
        #
        #  :<9 表示「左对齐，占 9 个字符宽度，不足补空格」。
        #  目的是让 role 列对齐，输出好看：
        #
        #      system    你是一位...
        #      user      我叫 Jack
        #      assistant 你好 Jack！
        #      ↑ 这几列是对齐的
        #
        #  规则：
        #      <  左对齐（默认就是左对齐，写出来更明确）
        #      >  右对齐
        #      ^  居中
        #      9  最小宽度
        #
        #  Java 类比：String.format("%-9s", role)
        #             ↑ 那个减号就是左对齐，和 Python 的 < 是一个意思
        # -----------------------------------------------------------
        print(f"  {i}. {msg['role']:<9} {preview}")


def main() -> int:
    """程序主流程。

    Returns:
        退出状态码。0 = 正常结束，1 = 配置错误，130 = 被 Ctrl+C 中断。
        这个码会通过 sys.exit() 传给操作系统，相当于 Java 里
        main 方法抛异常或 System.exit(code) 的效果。
    """
    args = parse_args()

    # ---------------------------------------------------------------
    #  1. 初始化客户端
    #
    #  ⚠️ 为什么要把初始化【单独】包一层 try？
    #
    #  因为配置类错误（Key 没填、Key 是占位符、格式不对）和
    #  网络类错误，对用户来说完全是两件事：
    #
    #      配置错   → 用户改 .env 就能解决，应该立刻告诉他
    #      网络错   → 发生在每次提问时，应该让他能重试
    #
    #  如果在进入循环后才初始化，配置错误就会在第一次提问时
    #  才暴露 —— 用户已经打了一堆字，却被一个本来可以提前发现
    #  的问题打断，体验很差。
    #
    #  这就是「快速失败（fail fast）」原则：
    #  能在启动阶段发现的问题，就不要留到运行阶段。
    #
    #  LLMError 是我们自己在 llm_client.py 里定义的异常，
    #  它的 message 已经是给人看的中文提示，直接 print 就行。
    # ---------------------------------------------------------------
    try:
        llm = LLMClient()
    except LLMError as exc:
        print(exc)
        return 1

    # ---------------------------------------------------------------
    #  2. 一次性算好「是否流式」，后面循环里直接用
    #
    #  为什么要反过来赋值？
    #  参数叫 --no-stream（表示"不要流式"），
    #  所以「要流式」= 没有传 --no-stream = not args.no_stream。
    #
    #  如果直接把这个判断写在循环里，每次循环都要算一遍，
    #  而且看代码的人要多绕一层脑子。提前转换成语义清晰的
    #  stream_mode，后面读起来就直白多了。
    # ---------------------------------------------------------------
    stream_mode = not args.no_stream
    print("=" * 64)
    print("  CLI AI Chat · Day 1 Challenge")
    print("=" * 64)
    # config.describe() 会显示模型/地址/Key 来源，但【不会泄露 Key 明文】
    print(f"  {llm.config.describe()}")
    print(f"  输出模式：{'流式 Streaming' if stream_mode else '一次性'}")
    print("  输入 exit 退出，/help 查看命令")
    print("=" * 64)

    # ---------------------------------------------------------------
    #  3. ⭐ 上下文列表 —— 整个程序的「记忆」就是它
    #
    #  ⚠️⚠️ 它必须建在 while 循环【外面】！
    #
    #      放在外面 → 列表在整个程序生命周期内一直存在
    #                 → 每轮往里面追加 → 记忆不断累积 ✅
    #
    #      放在里面 → 每轮循环开始时重新变成 []，上一轮全丢了
    #                 → 等于没有记忆 ❌
    #
    #  这是个很典型的「作用域决定生命周期」的坑。
    #  想验证的话，把这一行和下面的 system 追加挪到循环体开头，
    #  记忆立刻就失效了。
    #
    #  类型注解 list[Message] 只是给 IDE 和阅读者看的提示，
    #  Python 运行时不检查（这正是 day01_python_basics 里
    #  讲过的"动态类型"特征）。
    #
    #  Java 类比：这相当于把会话上下文存进 Redis 而不是
    #            方法内的局部变量 —— 区别就是"活多久"。
    # ---------------------------------------------------------------
    messages: list[Message] = []

    # system 消息永远是列表里的【第一条】，且只在初始化时加一次。
    # 为什么不放在循环里每轮都加？
    #   因为历史里重复出现多条相同 system 消息毫无意义，
    #   只会白白浪费 token 和上下文空间。
    if args.system:
        messages.append({"role": "system", "content": args.system})

    while True:
        # -----------------------------------------------------------
        #  读取用户输入
        #
        #  input("你：") 会先打印「你：」，然后阻塞等待你敲字并回车。
        #  返回的是你输入的内容（不含回车）。相当于 Java 的
        #  new BufferedReader(new InputStreamReader(System.in)).readLine()
        #
        #  ⚠️ 为什么要 try 包起来？因为有两种"输入流异常结束"的情况：
        #
        #    EOFError
        #        输入流被关闭，没有内容可读了。典型场景：
        #          - 用管道喂数据且数据已经读完（echo "hi" | python x.py）
        #          - 在 Linux/Mac 上按 Ctrl+D
        #        input() 会抛这个异常。
        #
        #    KeyboardInterrupt
        #        用户按了 Ctrl+C。Python 默认会把它变成一个异常，
        #        不处理的话就打印一大坨红色堆栈 —— 用户只是
        #        想退出程序，却被吓一跳。这里捕获后礼貌地说"再见"。
        #
        #  两个异常放在一个元组里捕获（Python 的写法），
        #  相当于 Java 的 catch (EOFException | InterruptedException e)。
        # -----------------------------------------------------------
        try:
            raw = input("\n你：")
        except (EOFError, KeyboardInterrupt):
            print("\n再见！")
            break  # break 跳出 while，直接走到函数末尾 return 0

        # -----------------------------------------------------------
        #  归一化用户输入
        #
        #  raw.strip() 去掉首尾的空白字符（空格、Tab、换行）。
        #  为什么需要？因为：
        #      "  exit  "  和  "exit"  应该被当成同一个命令
        #      "   "      这种"看起来输了其实没输"的内容应该被忽略
        #      （键盘上不小心多按了空格太常见了）
        #
        #  这是输入校验的第一道关：先归一化，再判断。
        # -----------------------------------------------------------
        text = raw.strip()

        # 空输入（原样是纯空白）→ 直接跳回循环开头重新等待输入。
        # continue 的含义是"跳过本轮剩下的代码，开始下一轮循环"。
        if not text:
            continue

        # -----------------------------------------------------------
        #  退出判断
        #
        #  text.lower() 转成小写，这样 EXIT / Exit / exit 都能识别。
        #  （用户不该因为大小写被卡住）
        #
        #  in EXIT_WORDS 做集合包含判断，O(1) 查找。
        #
        #  ⚠️ 注意这里【只判断，不清空 messages】——
        #     因为我们马上要退出了，清不清都无所谓。
        #     真正需要清空的是 /clear 命令（见下）。
        # -----------------------------------------------------------
        if text.lower() in EXIT_WORDS:
            print("再见！")
            break

        # -----------------------------------------------------------
        #  斜杠命令分发
        #
        #  以 "/" 开头的内容被当成「命令」而不是「要问模型的话」。
        #  这是 CLI 工具很常见的约定（参考 vim、Slack、Discord）。
        #
        #  为什么要设计这个机制？
        #  因为有些操作是给【程序】的（清空历史、查看状态），
        #  不是给【模型】的。混在一起会导致：
        #      - 模型不知道该怎么回应"清空历史"
        #      - 还得浪费一次 API 调用和 token
        #  所以本地能处理的事情，就不要绕一圈去问模型。
        # -----------------------------------------------------------
        if text.startswith("/"):
            # 同样转小写，让 /CLEAR 和 /clear 等效
            command = text.lower()

            if command == "/clear":
                # ---------------------------------------------------
                #  清空上下文，但【保留 system 消息】
                #
                #  这是个容易忽略的细节：
                #      简单粗暴的做法是  messages = []
                #      但那样会连人设一起丢掉，用户会突然感觉
                #      "AI 怎么变了个人"。
                #
                #  所以用条件表达式重新构造列表：
                #      有 system → [system 消息]
                #      没 system → []
                #
                #  ⚠️⚠️ 注意：这里用的是【重新赋值】而不是 messages.clear()
                #
                #      messages = [...]      ← 让变量指向一个新列表
                #      messages.clear()      ← 清空原来那个列表
                #
                #      在这个场景下两者效果一样，但理解区别很重要。
                #      一般推荐重新赋值：意图更清晰（就是"换一个新的"），
                #      而且如果别处还持有旧列表的引用，不会被意外清空。
                #
                #  这个"清空但保留人设"的语义，正是后面 Agent Memory
                #  里「系统提示词与会话历史分层管理」的雏形。
                # ---------------------------------------------------
                messages = [{"role": "system", "content": args.system}] if args.system else []
                print("[已清空上下文]")

            elif command == "/history":
                # 调用上面写好的函数，把上下文摊开展示
                show_history(messages)

            elif command == "/help":
                print(HELP_TEXT)

            else:
                # ---------------------------------------------------
                #  未知命令的友好提示
                #
                #  ⚠️ 关键：这里【必须 continue】，不能让它掉下去
                #     被当成普通提问发给模型。
                #
                #  如果漏了 continue，用户敲 /xyz 就会真的调用一次 API ——
                #  既浪费钱，又让模型去猜"/xyz 是什么意思"，
                #  行为非常诡异。
                # ---------------------------------------------------
                print(f"[未知命令：{text}，输入 /help 查看可用命令]")

            # 所有斜杠命令处理完都走到这里，跳过下面的"发请求"环节
            continue

        # ---------------------------------------------------------------
        #  4. ⭐ 把用户这句话追加进上下文
        #
        #  ⚠️ 顺序很重要：必须在【发请求之前】追加。
        #     否则这一轮模型看不到你刚说的话，等于自问自答。
        #
        #  role="user" 表示"这是用户说的话"。
        #  三个 role 的分工：
        #      system     人设/规则（只在开头出现一次）
        #      user       用户说的话
        #      assistant  模型说过的话
        #
        #  注意：这里【只是把话记进列表】，并没有发给模型。
        #  真正发出去是下面 create(messages=messages) 那一步 ——
        #  那时发出去的是【整个列表】，包含之前所有轮次。
        # ---------------------------------------------------------------
        messages.append({"role": "user", "content": text})

        # end="" 让光标停在同一行，flush=True 保证立即输出。
        # 这样流式返回的第一个字才能马上显示在 "AI：" 后面，
        # 而不是等缓冲区满了才一起冒出来。
        print("AI：", end="", flush=True)

        # ---------------------------------------------------------------
        #  time.perf_counter() 用于测量耗时
        #
        #  ⚠️ 为什么不用 time.time()？
        #
        #      time.time()        返回"墙上时钟"（当前时间戳）。
        #                         它受系统时间调整影响 ——
        #                         如果期间 NTP 校时或用户改了系统时间，
        #                         算出来的耗时可能是负数或离谱的值。
        #
        #      time.perf_counter() 返回一个【单调递增】的计时器，
        #                         专门用来测"过了多久"，精度也更高。
        #
        #  规律：测耗时永远用 perf_counter，不要用 time()。
        #
        #  Java 类比：System.nanoTime()（单调）而不是 System.currentTimeMillis()
        # ---------------------------------------------------------------
        start = time.perf_counter()

        # ---------------------------------------------------------------
        #  ⭐ 为什么要搞一个 pieces 列表？
        #
        #  因为流式接口返回的是【生成器】—— 一次只吐一小段，
        #  吐完就没了，不会给你一个完整的字符串。
        #
        #  但我们既要"边收边显示"（用户体验），
        #  又要"拿到完整回答"（存进上下文）。
        #  这两个需求只能靠：收到一小段就同时做两件事 ——
        #      ① 立刻 print 出去        → 满足体验
        #      ② 同时 append 进 pieces  → 满足保存
        #  循环结束后用 "".join(pieces) 拼成完整回答。
        #
        #  Java 类比：
        #      Flux<String> 订阅时既 onNext 打印，又收集进 StringBuilder，
        #      最后 toString() 拿到全量。思路完全一致。
        #
        #  清空/新建这个列表也很关键：它必须是【每轮独立的】。
        #  如果定义在循环外面，上一轮的内容会混进这一轮。
        # ---------------------------------------------------------------
        pieces: list[str] = []

        try:
            if stream_mode:
                # 逐块接收并显示
                for piece in llm.chat_stream(messages):
                    pieces.append(piece)  # 攒起来，备用
                    print(piece, end="", flush=True)  # 立刻显示出去
            else:
                # 非流式：一次拿到完整回答，同样塞进 pieces，
                # 这样后面 "".join(pieces) 的代码两种模式都能复用 ——
                # 不用写两套"存历史"的逻辑。
                answer = llm.chat(messages)
                pieces.append(answer)
                print(answer)

        except LLMError as exc:
            # -----------------------------------------------------------
            #  ⚠️⚠️ 失败时【必须回滚】刚才追加的那条 user 消息
            #
            #  为什么？看一个具体的坏情况：
            #
            #      第1轮  你：我叫 Jack     → 请求失败（网络抖了一下）
            #             此时 messages = [..., user: "我叫 Jack"]
            #             但【没有】对应的 assistant 回答
            #
            #      第2轮  你：我叫什么？    → messages 变成
            #             [user: "我叫 Jack", user: "我叫什么？"]
            #                                ↑ 两个 user 连着出现，中间没有回答
            #
            #  这会带来两个问题：
            #     1) 上下文结构是残缺的。正常对话是 user/assistant 成对，
            #        现在模型看到"用户连说两句却没人应"，容易理解混乱。
            #     2) 如果你的代码后面有"必须成对"的校验（很多框架会检查
            #        messages 交替出现），直接就会报错。
            #
            #  pop() 是列表的方法，弹出并返回最后一个元素。
            #  不传参数就是弹最后一个（相当于 Java 的 list.remove(list.size()-1)）。
            #
            #  这就是为什么前面要先 append 再做请求 ——
            #  "先记账，失败了再冲销"，比"成功了才记账"更好写，
            #  因为后者要在两个分支里都写一遍 append。
            #
            #  设计原则：让成功的路径最简洁，把复杂处理放到异常分支。
            # -----------------------------------------------------------
            messages.pop()
            print(f"\n{exc}")
            continue  # 本轮作废，回到循环开头等下一次输入

        except KeyboardInterrupt:
            # 用户在等待回答时按了 Ctrl+C。
            # 同样回滚 —— 这次回答是"用户主动取消"的，
            # 上下文里同样不该留下一个没有回答的问题。
            messages.pop()
            print("\n[已取消本次回答]")
            continue

        # 计时结束。perf_counter 的两次调用相减就是这一轮的耗时
        elapsed = time.perf_counter() - start
        print()  # 补一个换行，因为流式输出全程用的是 end=""

        # ---------------------------------------------------------------
        #  5. ⭐ 把模型的回答也追加进上下文，形成完整的一轮
        #
        #  ⚠️ 为什么 assistant 的话也必须存？
        #
        #  因为下一轮把历史发过去时，如果只有"用户问过什么"、
        #  没有"模型答过什么"，会出现：
        #
        #      [user: 我叫 Jack, user: 我叫什么？]
        #                          ↑ 两个 user 连着，模型看不到中间发生过什么
        #
        #  模型就不知道它之前说过"你好 Jack"，
        #  于是可能回答"我不知道你叫什么"—— 记忆就断了。
        #
        #  ⭐ 记住这个公式：
        #      一轮完整对话 = user + assistant，必须成对出现。
        #      这就是 Chat API 对"历史"的基本结构要求。
        #
        #  "".join(pieces) 把碎片列表拼成一个字符串：
        #      ["你", "好", " Jack"] → "你好 Jack"
        #
        #  等价写法：
        #      "".join(pieces)     ✅ 推荐，效率最高
        #      "".join([p for p in pieces])
        #      functools.reduce(...)  过度设计
        #
        #  ⚠️ 注意用 "" 而不是 " " 或 "\n" 连接 ——
        #     因为流式的每个 piece 已经是【文本的原样片段】了，
        #     可能切在任意位置（甚至半个字中间）。
        #     加任何分隔符都会把原来的文字弄坏。
        #
        #  Java 类比：String.join("", list) 或 StringBuilder 拼接
        # ---------------------------------------------------------------
        messages.append({"role": "assistant", "content": "".join(pieces)})

        # ---------------------------------------------------------------
        #  6. 状态栏：耗时 / token 用量 / 上下文长度
        #
        #  ⚠️ 这里的 messages 长度是【含 system 的】。
        #     比如 1 个 system + 3 轮对话(每轮2条) = 7 条。
        #     所以数字看起来会比"对话轮数"大，不是 bug。
        #
        #  :.1f 是 f-string 的格式规范：保留 1 位小数的浮点数。
        #      Java 类比：String.format("%.1f", elapsed)
        #
        #  llm.usage_text() 读的是 llm_client 内部记的"最近一次用量"，
        #  ⚠️ 它是【有状态的】—— 所以必须在这次请求之后、
        #     下次请求之前读，否则会被覆盖。
        #
        #  ⭐ 观察重点：留意"输入 token"是不是一轮比一轮大。
        #     那是历史在不断重发的直接证据，也是"记忆的代价"：
        #     上下文越长，每轮越慢、越贵，最终会撞上模型的上限。
        #     解法（截断/摘要/检索）就是后面 RAG 的动机所在。
        # ---------------------------------------------------------------
        print(f"[{elapsed:.1f}s · {llm.usage_text()} · 上下文 {len(messages)} 条]")

    # while 循环结束（用户输入了退出词，或 Ctrl+C / 输入流结束）
    return 0


# ---------------------------------------------------------------
#  程序入口守卫
#
#  为什么需要它？两个场景：
#
#    ① 直接运行：python chat.py
#       → __name__ == "__main__" → 调用 main() 跑起来  ✅
#
#    ② 被别人 import：from chat import show_history
#       → __name__ == "chat" → 不执行 main()
#       → 否则你一 import 它就弹出交互对话，完全没法当模块复用 ❌
#
#  Java 类比：Java 的 main 方法只有显式调用才跑，
#            但 Python 的"文件顶层代码"在 import 时就会执行，
#            所以才需要这个守卫来模拟 Java 的行为。
#
#  关于 sys.exit(main())：
#      sys.exit(code) 抛出一个 SystemExit 异常来终止进程，
#      code 会传给操作系统。0 表示正常，非 0 表示出错。
#      这样 shell / 批处理脚本就能判断你的程序是成功还是失败。
# ---------------------------------------------------------------
if __name__ == "__main__":
    sys.exit(main())
